-- NOX7: automatische Kampfkraft-Historie je Squad
-- Im Supabase SQL Editor einmal vollständig ausführen.

create table if not exists public.nox7_squad_power_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  squad_number smallint not null check (squad_number between 1 and 3),
  power bigint not null check (power >= 0),
  recorded_at timestamptz not null default now()
);

create index if not exists nox7_squad_power_history_lookup_idx
  on public.nox7_squad_power_history(user_id, squad_number, recorded_at);

alter table public.nox7_squad_power_history enable row level security;

drop policy if exists "NOX7 squad power history readable by owner and leadership"
  on public.nox7_squad_power_history;

create policy "NOX7 squad power history readable by owner and leadership"
on public.nox7_squad_power_history
for select to authenticated
using (
  user_id = auth.uid()
  or exists (
    select 1
    from public.profiles viewer
    where viewer.id = auth.uid()
      and viewer.status = 'active'
      and (
        viewer.game_rank in ('R4', 'R5')
        or (viewer.id = '9cd89136-4682-4e6a-84ba-43c41327fa93'::uuid and viewer.role = 'admin')
      )
  )
);

create or replace function public.nox7_record_squad_power_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  n smallint;
  new_power bigint;
  old_power bigint;
begin
  for n in 1..3 loop
    if n = 1 then
      new_power := new.squad1_power;
      if tg_op = 'UPDATE' then old_power := old.squad1_power; else old_power := null; end if;
    elsif n = 2 then
      new_power := new.squad2_power;
      if tg_op = 'UPDATE' then old_power := old.squad2_power; else old_power := null; end if;
    else
      new_power := new.squad3_power;
      if tg_op = 'UPDATE' then old_power := old.squad3_power; else old_power := null; end if;
    end if;

    if new_power is not null and (tg_op = 'INSERT' or new_power is distinct from old_power) then
      insert into public.nox7_squad_power_history(user_id, squad_number, power)
      values (new.id, n, new_power);
    end if;
  end loop;
  return new;
end;
$$;

drop trigger if exists nox7_profiles_squad_power_history on public.profiles;

create trigger nox7_profiles_squad_power_history
after insert or update of squad1_power, squad2_power, squad3_power
on public.profiles
for each row
execute function public.nox7_record_squad_power_history();

-- Bestehende Squad-Werte als Startpunkt übernehmen, sofern noch kein Verlauf existiert.
insert into public.nox7_squad_power_history(user_id, squad_number, power, recorded_at)
select p.id, v.squad_number, v.power, coalesce(p.updated_at, now())
from public.profiles p
cross join lateral (
  values
    (1::smallint, p.squad1_power),
    (2::smallint, p.squad2_power),
    (3::smallint, p.squad3_power)
) as v(squad_number, power)
where v.power is not null
  and not exists (
    select 1
    from public.nox7_squad_power_history h
    where h.user_id = p.id
      and h.squad_number = v.squad_number
  );
