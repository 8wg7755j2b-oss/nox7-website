-- NOX7: automatische Kampfkraft-Historie
-- In Supabase SQL Editor ausführen.
create table if not exists public.nox7_power_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  power bigint,
  recorded_at timestamptz not null default now()
);
create index if not exists nox7_power_history_user_time_idx
  on public.nox7_power_history(user_id, recorded_at);

alter table public.nox7_power_history enable row level security;

drop policy if exists "NOX7 power history readable by owner and leadership" on public.nox7_power_history;
create policy "NOX7 power history readable by owner and leadership"
on public.nox7_power_history for select to authenticated
using (
  user_id = auth.uid()
  or exists (
    select 1 from public.profiles viewer
    where viewer.id = auth.uid()
      and viewer.status = 'active'
      and (
        (viewer.id = '9cd89136-4682-4e6a-84ba-43c41327fa93'::uuid and viewer.role = 'admin')
        or viewer.game_rank in ('R4','R5')
      )
  )
);

create or replace function public.nox7_record_power_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.power is distinct from old.power and new.power is not null then
    insert into public.nox7_power_history(user_id, power)
    values (new.id, new.power);
  end if;
  return new;
end;
$$;

drop trigger if exists nox7_profiles_power_history on public.profiles;
create trigger nox7_profiles_power_history
after update of power on public.profiles
for each row execute function public.nox7_record_power_history();

-- Ein Startwert pro bestehendem Profil, damit die Kurve nicht leer beginnt.
insert into public.nox7_power_history(user_id, power, recorded_at)
select p.id, p.power, coalesce(p.updated_at, now())
from public.profiles p
where p.power is not null
  and not exists (
    select 1 from public.nox7_power_history h where h.user_id = p.id
  );
