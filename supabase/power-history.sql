-- NOX7: Verlauf der Gesamtkampfkraft
create table if not exists public.nox7_power_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  power bigint not null check (power >= 0),
  recorded_at timestamptz not null default now()
);
create index if not exists nox7_power_history_user_time_idx
  on public.nox7_power_history(user_id, recorded_at);

alter table public.nox7_power_history enable row level security;

drop policy if exists "power history readable by owner and leadership" on public.nox7_power_history;
create policy "power history readable by owner and leadership"
on public.nox7_power_history for select to authenticated
using (
  user_id = auth.uid()
  or exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.status = 'active'
      and (p.game_rank in ('R4','R5') or (p.id = '9cd89136-4682-4e6a-84ba-43c41327fa93'::uuid and p.role = 'admin'))
  )
);

create or replace function public.capture_nox7_power_history()
returns trigger language plpgsql security definer
set search_path = public
as $$
begin
  if new.power is not null and (
    tg_op = 'INSERT' or old.power is distinct from new.power
  ) then
    insert into public.nox7_power_history(user_id, power, recorded_at)
    values (new.id, new.power, now());
  end if;
  return new;
end;
$$;

drop trigger if exists trg_capture_nox7_power_history on public.profiles;
create trigger trg_capture_nox7_power_history
after insert or update of power on public.profiles
for each row execute function public.capture_nox7_power_history();

-- Seed the current power as the first point for existing profiles.
insert into public.nox7_power_history(user_id, power, recorded_at)
select p.id, p.power, now()
from public.profiles p
where p.power is not null
  and not exists (select 1 from public.nox7_power_history h where h.user_id = p.id);
